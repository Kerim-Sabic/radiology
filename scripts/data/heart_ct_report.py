"""Writes docs/data/heart-ct-report.md from docs/data/heart-ct-cases.json and the built pack.

  python scripts/data/heart_ct_report.py
"""
from __future__ import annotations

import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
facts = json.loads((ROOT / "docs/data/heart-ct-cases.json").read_text(encoding="utf-8"))
man = json.loads((ROOT / "public/packs/heart-ct/pack.json").read_text(encoding="utf-8"))
les = json.loads((ROOT / "public/packs/heart-ct/lessons.json").read_text(encoding="utf-8"))
packdir = ROOT / "public/packs/heart-ct"
files = sum(1 for p in packdir.rglob("*") if p.is_file())
size = sum(p.stat().st_size for p in packdir.rglob("*") if p.is_file())
n_ai = sum(1 for t in man["referenceTargets"] if t["provenance"] == "ai_draft")
n_ex = len(man["referenceTargets"]) - n_ai
L = []
w = L.append


def counts(key):
    c = collections.Counter(f[key] for f in facts.values())
    return ", ".join(f"{k} {v}" for k, v in sorted(c.items(), key=lambda kv: str(kv[0])))


w("# Heart and great vessels on chest CT (`heart-ct`)\n")
w("Generated by `scripts/data/heart_ct_report.py` from `docs/data/heart-ct-cases.json` (written by `scripts/data/heart_ct_build.py`).\n")
w("## Summary\n")
w(f"- {len(man['series'])} chest CTs of adults, {sum(len(s['instances']) for s in man['series'])} DICOM slices, {files} files, {size / 1e6:.1f} MB "
  f"(budget 250 MB / about 3,000 files; hard stop 400 MB / 5,000 files). {n_ex} dataset outlines and {n_ai} AI outlines; "
  f"{len(les['cases'])} lesson cases, {len(les['tasks'])} tasks.")
w("- Source: TotalSegmentator CT dataset v3.0.0, Zenodo record 22688904 (re-read from the Zenodo API on 2026-11-09: version 3.0.0, 1,939 CTs, "
  "`Totalsegmentator_dataset_v300.zip`, 37,415,622,057 bytes, licence cc-by-4.0, md5 0728beea76475e92cdb3160e228265d1). Read with HTTP range "
  "requests: the 35 MB central directory once, then `meta.csv` and, per case, only the members the pack uses (about 1 GB in total; the Zenodo "
  "rate limit is handled by waiting for `Retry-After`). Every member is checked against its zip CRC-32.")
w("- Pixel data: the dataset's CTs are 1.5 mm isotropic NIfTI. Each case is cropped in plane to the body and in z from about 20 mm above the "
  "top of the aortic arch (up to the arch branches, never into the neck) to 12 mm below the heart, every second slice kept (3 mm), HU clipped "
  "to -1024..3071, stored as unsigned 12-bit values with Rescale Intercept -1024, JPEG-LS lossless. Cropping and thinning are why 36 cases fit "
  "the budget (full 1.5 mm stacks would be several GB).")
w("- Identity: PatientName blank, PatientID `HCT-<hash>`, StudyDescription `CT chest`, neutral lesson titles `Patient <code> · Chest CT`. Age and sex "
  "come from the dataset table. The reading-room texts are checked against a leak pattern (dataset names, diagnosis words) at build time.\n")
w("## Selection\n")
w("Candidates came from `meta.csv`: adults, `study_type` among heart, aortic valve, atrium, coronary arteries, thoracic aorta, angiography of the "
  "chest and routine chest types; pathology `bleeding` and `unclear` excluded. 333 candidates were screened from their own segmentations: "
  "heart, aorta, pulmonary vein and both venae cavae all non-empty, heart at least 3 voxels from the field-of-view edges in plane and 4 slices "
  "from the ends, heart volume 150 to 1200 ml (275 had all five structures, 233 passed the field of view). From those 51 candidates were chosen "
  "to balance institute (the dataset is about 80 % Basel, so other hospitals were taken whenever eligible), scanner (all the eligible GE cases "
  "chosen; no eligible Philips or Toshiba case), study type and pathology tag; 36 were kept after the contrast check and the size budget.")
w("Contrast is measured, not assumed: median HU of the dataset's aorta outline over the heart's levels, >= 150 HU = contrast-enhanced "
  "(as in docs/data/vessel-drafts-report.md). The dataset has no contrast field.\n")
n_c = sum(1 for f in facts.values() if f["contrast"])
w(f"- Contrast-enhanced: {n_c}. Not enhanced: {len(facts) - n_c}, of which clearly unenhanced (aorta <= 60 HU): "
  f"{sum(1 for f in facts.values() if f['aortaMedianHuAtHeart'] <= 60)}; faint or late contrast (60 to 150 HU): "
  f"{sum(1 for f in facts.values() if 60 < f['aortaMedianHuAtHeart'] < 150)}.")
w(f"- Institutes: {counts('institute')}. Manufacturers: {counts('manufacturer')}.")
vasc = [k for k, v in facts.items() if v["metaPathology"] == "vascular"]
big = [k for k in vasc if facts[k]["aortaMaxInscribedDiameterMm"] >= 42 and "thorax" in facts[k]["metaPathologyLocation"]]
w("- Pathology: the dataset's table records only a coarse tag (`vascular`, `tumor`, ...) with an organ system, never aneurysm, dissection or "
  f"pulmonary embolus. No case is called a dissection or an embolus. {len(vasc)} cases carry the tag `vascular`; "
  f"{len(big)} of them ({', '.join(big)}) also have an aorta whose largest inscribed circle is "
  f"{min(facts[k]['aortaMaxInscribedDiameterMm'] for k in big):.0f} to {max(facts[k]['aortaMaxInscribedDiameterMm'] for k in big):.0f} mm, "
  "and are taught as 'a widened aorta' with the measurement, not as an aneurysm or dissection (`s1133`, 52 mm with heterogeneous content in "
  "the descending aorta on the images, is the clearest). A pulmonary-embolus case cannot be identified from the dataset's metadata, so none is "
  "included (the `pe-cta` pack covers it).\n")
w("## Labels\n")
w("**Dataset outlines** (`provenance: source_automated`): heart, aorta, left atrial appendage, pulmonary veins, venae cavae, brachiocephalic trunk, "
  "both brachiocephalic veins, carotids and subclavians, those that lie inside the cropped chest. The dataset's paper (Wasserthal et al., "
  "Radiology: AI 2023, Data Annotation) says: first segmentations from public models or an iteratively retrained nnU-Net, then manually reviewed "
  "and corrected where necessary, supervised by two physicians with 3 and 6 years of body-imaging experience; version 3.0.0 refined many labels. "
  "`provenanceDetail` says exactly that: model-assisted and radiologist-verified, not drawn from scratch, not re-reviewed here. Only the largest "
  "connected part is kept (up to four for pulmonary veins, two for brachiocephalic veins) and the left/right order of paired vessels is checked on "
  "the centroids.\n")
w("**AI drafts** (`provenance: ai_draft`, layer `atlas`, source Horalix, never graded): left ventricular myocardium, left and right atrium, left and "
  "right ventricle, pulmonary arteries.\n")
w("- Tool: MONAI model-zoo bundle `wholeBody_ct_segmentation` v0.1.9 (SegResNet, 1.5 mm weights `model.pt`), licence Apache-2.0 (bundle LICENSE), "
  "trained on the TotalSegmentator dataset v1 (Zenodo 6802614, CC BY 4.0): the model the anatomy atlas already uses. Normalisation over the whole "
  "volume, inference inside the heart's box + 30 mm. torch 2.11.0+cu128, MONAI 1.6.1, nibabel 5.4.2.")
w("- GPUs: two RTX 5080 (driver 610.88), one worker process per GPU (`heart_ct_ai.py <gpu> <cases>`): 36 cases, mean 1.0 s and at most 3.1 s per case "
  "including loading and normalising the volume (the network itself takes under a second). The first GPU was shared with another job (8.8 GB in use).")
w("- **Not run: TotalSegmentator's licensed tasks `heartchambers_highres` and `coronary_arteries`.** The tool's own offline licence check "
  "(`has_valid_license_offline`, which never returns the number) reported `missing_license` for `totalseg-home` and for every other TotalSegmentator "
  "home folder on this machine, and both tasks exit with the tool's licence message without it. The configuration file was never opened and no "
  "workaround was attempted. Consequence: there are **no coronary-artery outlines**, and the chambers come from the licence-free bundle above. "
  "To add them: enter the licence number with the tool's own `totalseg_set_license`, then run the two tasks on "
  "`work/heart-ct/<case>/ct_crop.nii.gz` (see `scripts/data/heart_ct_ai.py`).")
w("- Rules (as the atlas's chamber QC): chambers only on contrast studies; one connected part; plausible volume (atria 20-250 ml, ventricles 40-350 ml, "
  "muscle 60-400 ml, pulmonary arteries 15-160 ml inside the crop); at least 90 % inside the heart outline dilated by 2 voxels; blood-pool median >= 120 HU "
  "and >= 40 HU above the muscle; left atrium left of the right atrium, left ventricle left of the right ventricle and of the right atrium, left atrium and "
  "left ventricle behind the right ventricle; pulmonary artery in front of the aorta's centre and near the top of the heart, >= 60 HU. The model's aorta "
  "was not used (the dataset's aorta outline is better).\n")
w("## Quality control by eye\n")
w("Every case was rendered with `scripts/data/heart_ct_qc.py` (four axial levels, coronal and sagittal reformats rasterised from the stored polygons) and "
  "all 36 sheets were looked at. Outlines sit on the right structures and the right side in all 36. Weak points seen and left in (unreviewed AI drafts): the AI "
  "left ventricle is small on the four-chamber slice of `s1372` and `s0825`; the dataset's heart outline in `s0911` has a small connected anterior part. "
  "The chamber thresholds were relaxed once (blood-pool 150 -> 120 HU and 'above the muscle' rule; pulmonary artery 100 -> 60 HU) and the newly included "
  "chambers were checked again by eye.\n")
dropped = []
for cid, f in facts.items():
    for k, v in f["ai"].items():
        if isinstance(v, str) and k != "_all" and v != "no output":
            dropped.append(f"{cid} {k.replace('heart_', '')} ({v.replace('dropped: ', '').split(';')[0]})")
w("Dropped because they failed a rule:")
w("- AI structures: " + "; ".join(dropped))
none = [cid for cid, f in facts.items() if f["contrast"] and not any(isinstance(v, dict) for v in f["ai"].values())]
w("- Chamber model without usable output on a contrast study (nothing returned, or outlines outside the heart): " + ", ".join(none) +
  ". Their dataset outlines are kept; they get no chamber lesson.")
w("- Chamber model not run on studies without a clear contrast injection: " +
  ", ".join(cid for cid, f in facts.items() if not f["contrast"]) + " (blood and heart muscle cannot be told apart).")
w("- Dataset outlines not in the cropped chest (gated studies end below the arch; the right carotid and subclavian are often cut off): see the table.")
w("- No case was dropped for failing QC; 15 of the 51 candidates were not used to stay inside the size budget or because a better-matched case of the "
  "same kind was available.\n")
w("## Cases\n")
w("| case | institute | scanner | dataset study tag (pathology tag) | age | aorta HU | contrast | widest aorta mm | slices | dataset outlines | AI outlines | AI dropped or not run |")
w("|---|---|---|---|---|---|---|---|---|---|---|---|")
for cid, f in facts.items():
    ex = [k for k, v in f["expert"].items() if isinstance(v, dict)]
    ai = [k for k, v in f["ai"].items() if isinstance(v, dict)]
    dr = [k.replace("heart_", "") for k, v in f["ai"].items() if isinstance(v, str) and k != "_all"]
    nr = f["ai"].get("_all", "")
    w(f"| {cid} | {f['institute']} | {f['manufacturer']} {f['scanner']} | {f['studyType']} ({f['metaPathology']}) | {int(f['age'])} | "
      f"{f['aortaMedianHuAtHeart']:.0f} | {'yes' if f['contrast'] else 'no'} | {f['aortaMaxInscribedDiameterMm']:.0f} | {f['slices']} | {len(ex)} | "
      f"{len(ai)} | {', '.join(dr) or nr[:50]} |")
w("\n## Lessons\n")
cnt = collections.Counter(t["id"].split(":")[1] for t in les["tasks"])
w("Tasks per kind: " + ", ".join(f"{k} {v}" for k, v in sorted(cnt.items())) + ". Naming tasks are `exploratory_self_review` against the dataset outlines "
  "(model-assisted, not authoritative); chamber tasks are self-review with the AI outlines only as a late hint; contrast and aorta-size tasks are choice "
  "questions answered from the measured HU and the largest inscribed circle. Nothing is made free (`server/free.ts` untouched).\n")
w("## Licence notes\n")
w("- Dataset: CC BY 4.0; attribution in the `pack.json` sources and on the credits page (Wasserthal et al., Radiology: AI 2023; dataset DOI 10.5281/zenodo.22688904).")
w("- MONAI bundle: Apache-2.0 (weights and code), trained on CC BY 4.0 data; no student-visible text names the tool or the model (the source is `horalix`).")
w("- TotalSegmentator licensed tasks: the public README, read on 2026-11-09, gives a free licence for non-commercial use and asks commercial users to contact the "
  "author. The owner states he holds permission for the paid product; that cannot be verified from the repository and the tool's own check found no licence number, "
  "so these tasks were not run.")
(ROOT / "docs/data/heart-ct-report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote docs/data/heart-ct-report.md")
