// Writes src/content/freeTasks.generated.ts: the question of every free task that has a first picture (a poster in
// public/landing/posters), so the case preview can show it while the reading room and the catalogue still download.
//   node scripts/build/freeTasks.mjs
// tests/freeTasks.test.ts fails if the file no longer matches the lessons.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const posters = new Set(readdirSync(`${root}public/landing/posters`).filter((f) => f.endsWith('.webp')).map((f) => f.slice(0, -5).replace('--', ':')));
const index = JSON.parse(readFileSync(`${root}public/packs/index.json`, 'utf8'));
const tasks = {};
for (const pack of index.packs) {
  const file = `${root}public/packs/${pack.lessons}`;
  if (!pack.lessons || !existsSync(file)) continue;
  for (const t of JSON.parse(readFileSync(file, 'utf8')).tasks ?? []) {
    if (!posters.has(t.id)) continue;
    const required = (t.targets ?? []).filter((x) => x.required);
    const target = required[0]?.name ?? t.targets?.[0]?.name;
    // The same rule as the reading room's "Tap the …" hint: one point on one structure.
    const tap = t.grading?.kind === 'point_in_target' && required.length <= 1 && target ? `Tap the ${target.toLowerCase()}` : null;
    tasks[t.id] = { title: t.title, prompt: t.prompt, tap };
  }
}
const ids = Object.keys(tasks).sort();
const body = `// Generated by \`node scripts/build/freeTasks.mjs\` from the lessons of the free cases. Do not edit by hand.
// The question of each free task with a first picture, for the case preview (src/components/RoomPreview.tsx).
export const FREE_TASK_TEXT: Record<string, { title: string; prompt: string; tap: string | null }> = ${JSON.stringify(Object.fromEntries(ids.map((id) => [id, tasks[id]])), null, 2)};
`;
writeFileSync(`${root}src/content/freeTasks.generated.ts`, body);
console.log(`freeTasks.generated.ts: ${ids.length} tasks`);
