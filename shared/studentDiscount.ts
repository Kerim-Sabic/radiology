export const STUDENT_PRICES = { monthly: 14, yearly: 105 } as const;

/** Match a full academic namespace, never a lookalike such as university.edu.example.com. */
export function academicEmail(email: unknown): boolean {
  if (typeof email !== 'string') return false;
  const parts = email.trim().toLowerCase().split('@');
  if (parts.length !== 2 || !parts[0] || /\s/.test(parts[0])) return false;
  const domain = parts[1];
  if (domain.length > 253 || !domain.split('.').every(label => /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(label))) return false;
  return [...ACADEMIC_SUFFIXES].some(suffix => domain.endsWith(`.${suffix}`));
}
